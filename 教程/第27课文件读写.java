// 第27课 文件读写
// 目标：用 文件助手 读写 UTF-8 文本文件；请在仓库根目录运行，文件会写到 构建/教程 下。
文件路径 目标 = 文件路径.取("构建", "教程", "第27课.txt");

尝试 {
    文件助手.建目录(目标.取上级());
    文件助手.写文本(目标, "第一行：中文 Java\n第二行：文件读写\n");
    打印行("写入成功：{目标.转绝对路径()}");

    字符串 读回 = 文件助手.读文本(目标);
    打印行("读回内容：");
    打印(读回);

    打印行("行数：{文件助手.读所有行(目标).元素数()}");
    打印行("文件存在：{文件助手.存在(目标)}");
} 捕获 (输入输出异常 异常) {
    打印行("文件操作失败：{异常.取消息()}");
}
