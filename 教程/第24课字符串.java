// 目标：字符串 常用方法、拆分与拼接、文本构建器。
字符串 原句 = "  Java 中文编程  ";
字符串 修剪后 = 原句.修剪();

打印行("原长度：{原句.长度()}，修剪后长度：{修剪后.长度()}");
打印行("大写：{修剪后.转大写()}");
打印行("包含 Java：" + 修剪后.含有("Java"));
打印行("以 Java 开头：" + 修剪后.以开头("Java"));
打印行("替换结果：" + 修剪后.替换("Java", "中文 Java"));
打印行("取前四个字符：" + 修剪后.取子串(0, 4));

字符串[] 片段 = 修剪后.拆分(" ");
打印行("片段个数：{片段.长度}");
打印行("拼接：" + 字符串.拼接(" / ", 片段));

