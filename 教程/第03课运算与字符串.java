// 第03课 运算与字符串
// 目标：算术运算、整数除法与取余、类型转换、字符串拼接与插值。
整数 甲 = 17;
整数 乙 = 5;

整数 和 = 甲 + 乙;
整数 差 = 甲 - 乙;
整数 积 = 甲 * 乙;
整数 商 = 甲 / 乙; // 忽略提示 CJK105：本课专门演示整数除法
整数 余数 = 甲 % 乙;
双浮点 精确商 = (双浮点) 甲 / 乙;

打印行("和：{和}");
打印行("差：{差}");
打印行("积：{积}");
打印行("整数除法商：{商}，余数：{余数}");
打印行("精确商：{精确商}");

字符串 标题 = "运算演示";
// 拼接写法（本节教学点）
字符串 明细 = 标题 + "：" + 甲 + " + " + 乙 + " = " + 和;
打印行(明细);
// 同样的拼接可以写成插值，更接近自然语言
打印行("{标题}：{甲} + {乙} = {和}");

和 += 3;
和--;
打印行("自增自减后：{和}");
