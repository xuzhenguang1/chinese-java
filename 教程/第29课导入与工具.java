// 第29课 导入与工具
// 目标：配合 算术、集合助手 与 可选值 等工具。
清单<字符串> 工具 = 数组清单.从("算术", "集合助手", "可选值");

打印行("绝对值：{算术.绝对值(-7)}");
打印行("最大值：" + 算术.最大(3, 9));
打印行("最小值：" + 算术.最小(3, 9));
打印行("平方根：{算术.平方根(144)}");
打印行("2 的 10 次方：" + 算术.幂(2, 10));
打印行("圆周率：{算术.圆周率}");
打印行("随机整数：" + (整数) (算术.随机() * 100));

集合助手.排序(工具);
打印行("已排序：{工具}");

可选值<字符串> 首个 = 工具.流().找首个();
首个.存在时(名称 -> 打印行("首个工具：" + 名称));

可选值<字符串> 未命中 = 可选值.空();
打印行("未命中默认：" + 未命中.或("没有"));
打印行("是否为空容器：{未命中.是空()}");
