    private static String 去后缀(String 文件名) {
        String 名 = 文件名.replace('\\', '/');
        int 斜杠 = 名.lastIndexOf('/');
        if (斜杠 >= 0) {
            名 = 名.substring(斜杠 + 1);
        }
        if (名.endsWith(".java")) {
            名 = 名.substring(0, 名.length() - 5);
        }
        return 名.isEmpty() ? "程序" : 名;
    }

