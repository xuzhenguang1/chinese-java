    private void 分析全部() {
        for (类符号 类 : new ArrayList<>(类表.values())) {
            if (类.隐式 || 类.合成) {
                continue;
            }
            分析静态初始化(类);
            分析字段初始化(类);
            if (类.构造器.isEmpty() && 类.字段.stream().anyMatch(字段 -> 字段.初值 != null)) {
                方法符号 默认 = new 方法符号(类, "<构造>", false, 类型.无, List.of(),
                        new 语法树.块(List.of()));
                默认.是构造器 = true;
                类.构造器.add(默认);
            }
            for (方法符号 构造器 : 类.构造器) {
                if (构造器.中间 == null) {
                    构造器.中间 = 分析方法(类, 构造器);
                }
                构造器.中间 = 附加构造前置(类, 构造器.中间);
            }
            for (方法符号 方法 : 类.方法) {
                if (方法.体 == null || 方法.中间 != null) {
                    continue;
                }
                方法.中间 = 分析方法(类, 方法);
            }
        }
    }

    private void 分析字段初始化(类符号 类) {
        if (类.字段.stream().noneMatch(字段 -> 字段.初值 != null)) {
            return;
        }
        类符号 旧类 = 当前类;
        方法符号 旧方法 = 当前方法;
        当前类 = 类;
        当前方法 = new 方法符号(类, "<字段初始化>", false, 类型.无, List.of(), null);
        作用域.clear();
        推入();
        try {
            定义("这", 类.类型);
            for (字段符号 字段 : 类.字段) {
                if (字段.初值 == null) {
                    continue;
                }
                字段.中间初值 = 分析表达式(字段.初值);
            }
        } finally {
            弹出();
            当前类 = 旧类;
            当前方法 = 旧方法;
        }
    }

    private 中间代码.方法 附加构造前置(类符号 类, 中间代码.方法 方法) {
        List<中间代码.语句> 前置 = new ArrayList<>();
        if (类.外部 != null && !类.静态嵌套) {
            前置.add(new 中间代码.表达式语句(new 中间代码.赋值(类.外部.类型,
                    new 中间代码.字段读(类.外部.类型,
                            new 中间代码.变量读(类.类型, "这"), "__外部"),
                    new 中间代码.变量读(类.外部.类型, "__外部"))));
        }
        for (字段符号 字段 : 类.字段) {
            if (字段.中间初值 == null || "__外部".equals(字段.名)) {
                continue;
            }
            前置.add(new 中间代码.表达式语句(new 中间代码.赋值(字段.类型,
                    new 中间代码.字段读(字段.类型,
                            new 中间代码.变量读(类.类型, "这"), 字段.名),
                    字段.中间初值)));
        }
        if (前置.isEmpty()) {
            return 方法;
        }
        List<中间代码.语句> 体 = new ArrayList<>(前置);
        if (方法.体() instanceof 中间代码.块 块) {
            体.addAll(块.语句());
        } else if (方法.体() != null) {
            体.add(方法.体());
        }
        return new 中间代码.方法(方法.名(), 方法.静态(), 方法.返回类型(), 方法.参数(),
                new 中间代码.块(体));
    }

    private void 分析静态初始化(类符号 类) {
        类符号 旧类 = 当前类;
        方法符号 旧方法 = 当前方法;
        当前类 = 类;
        当前方法 = new 方法符号(类, "<静态初始化>", true, 类型.无, List.of(), null);
        作用域.clear();
        临时序号 = 0;
        当前行 = 0;
        推入();
        try {
            for (静态字段符号 字段 : 类.静态字段) {
                if (字段.初值 == null) {
                    continue;
                }
                字段.中间初值 = 分析表达式(字段.初值);
                类型 值类型 = 类型(字段.中间初值);
                if (!可赋值(字段.类型, 值类型)) {
                    失败("静态字段「" + 类.名 + "." + 字段.名 + "」不能把「" + 值类型.文本()
                            + "」赋给「" + 字段.类型.文本() + "」。");
                }
            }
            for (枚举常量符号 常量 : 类.枚举常量) {
                for (语法树.表达式 实参 : 常量.实参) {
                    常量.中间实参.add(分析表达式(实参));
                }
            }
        } finally {
            弹出();
            当前类 = 旧类;
            当前方法 = 旧方法;
        }
    }

    private 中间代码.方法 分析方法(类符号 类, 方法符号 符号) {
        类符号 旧类 = 当前类;
        方法符号 旧方法 = 当前方法;
        Deque<Map<String, 类型>> 旧作用域 = new ArrayDeque<>(作用域);
        int 旧临时 = 临时序号;
        当前类 = 类;
        当前方法 = 符号;
        作用域.clear();
        临时序号 = 0;
        当前行 = 0;
        推入();
        try {
            if (!符号.静态) {
                定义("这", 类.类型);
            }
            for (中间代码.参数 参数 : 符号.参数) {
                定义(参数.名(), 参数.类型());
            }
            中间代码.语句 体 = 分析语句(符号.体);
            return new 中间代码.方法(符号.名, 符号.静态, 符号.返回类型, 符号.参数, 体);
        } finally {
            弹出();
            作用域.clear();
            作用域.addAll(旧作用域);
            临时序号 = 旧临时;
            当前类 = 旧类;
            当前方法 = 旧方法;
        }
    }

