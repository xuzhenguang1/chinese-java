    private void 收集(编译单元 单元) {
        注册内建类();
        for (类型声明 声明 : 单元.类型()) {
            收集类(声明, null);
        }
        if (单元.类型().isEmpty()) {
            类符号 脚本 = new 类符号(文件名);
            方法符号 入口 = new 方法符号(脚本, "<入口>", true, 类型.无, List.of(),
                    new 语法树.块(单元.语句()));
            脚本.方法.add(入口);
            类表.put(脚本.名, 脚本);
        }
    }

    /** 隐式根类与内建异常类：只参与类型检查，不生成 MIR 类定义。 */
    private void 注册内建类() {
        if (!类表.isEmpty()) {
            return;
        }
        类符号 对象 = new 类符号("对象", true);
        类表.put(对象.名, 对象);
        类符号 异常 = 内建类("异常", "对象");
        异常.字段.add(new 字段符号(类型.文本, "消息", "异常"));
        内建类("运行时异常", "异常");
        内建类("算术异常", "运行时异常");
        内建类("空指针异常", "运行时异常");
        内建类("数组越界异常", "运行时异常");
        内建类("非法参数异常", "运行时异常");
        内建类("数字格式异常", "运行时异常");
        内建类("类转换异常", "运行时异常");
        内建类("输入输出异常", "运行时异常");
    }

    private 类符号 内建类(String 名, String 父类) {
        类符号 类 = new 类符号(名, true);
        类.父类 = "对象".equals(父类) ? null : 父类;
        类表.put(名, 类);
        return 类;
    }

    private void 收集类(类型声明 声明, 类符号 外部) {
        String 英文种类 = 词表.中文到英文.getOrDefault(声明.种类(), 声明.种类());
        boolean 是接口 = 英文种类.equals("interface");
        boolean 是枚举 = 英文种类.equals("enum");
        boolean 是记录 = 英文种类.equals("record");
        if (!是接口 && !是枚举 && !是记录 && !英文种类.equals("class")) {
            不支持("「" + 声明.种类() + "」类型");
        }
        String 名 = 外部 == null ? 声明.名() : 外部.名 + "$" + 声明.名();
        类符号 已有 = 类表.get(名);
        if (已有 != null && !已有.隐式) {
            失败("重复的类名「" + 声明.名() + "」。");
        }
        类符号 类 = new 类符号(名);
        类.是接口 = 是接口;
        类.枚举 = 是枚举;
        类.记录 = 是记录;
        类.外部 = 外部;
        类.抽象 = 是接口 || 声明.修饰符().contains("abstract");
        类.父类 = 声明.父类() == null || "对象".equals(声明.父类().名())
                ? null : 查找类名(声明.父类().名());
        for (类型引用 接口 : 声明.接口()) {
            类.接口.add(查找类名(接口.名()));
        }
        for (类型参数 参数 : 声明.类型参数()) {
            类.类型参数名.add(参数.名());
        }
        类表.put(名, 类);
        java.util.Set<String> 旧参数 = new java.util.HashSet<>(类型参数名);
        if (外部 != null) {
            类型参数名.addAll(外部.类型参数名);
        }
        类型参数名.addAll(类.类型参数名);
        类符号 旧当前类 = 当前类;
        try {
            boolean 静态嵌套 = 外部 == null || 声明.修饰符().contains("static")
                    || 是接口 || 是枚举 || 是记录;
            类.静态嵌套 = 静态嵌套;
            当前类 = 类;
            if (外部 != null && !静态嵌套) {
                类.字段.add(new 字段符号(外部.类型, "__外部", 类.名));
            }
            for (语法树.枚举常量 常量 : 声明.枚举常量()) {
                类.枚举常量.add(new 枚举常量符号(常量.名(), 常量.实参()));
            }
            if (是枚举) {
                类.字段.add(new 字段符号(类型.文本, "__枚举名", 类.名));
            }
            if (是记录) {
                收集记录分量(类, 声明);
            }
            for (成员 成员 : 声明.成员()) {
                if (成员 instanceof 类型声明 内嵌) {
                    收集类(内嵌, 类);
                } else if (成员 instanceof 字段声明 字段) {
                    收集字段(类, 字段);
                } else if (成员 instanceof 方法声明 方法) {
                    收集方法(类, 方法);
                } else if (成员 instanceof 构造器声明 构造器) {
                    收集构造器(类, 构造器);
                } else if (成员 instanceof 入口声明 入口) {
                    类.方法.add(new 方法符号(类, "<入口>", true, 类型.无, List.of(), 入口.体()));
                }
            }
            if (是记录) {
                收集记录方法(类);
            } else if (外部 != null && !静态嵌套 && 类.构造器.isEmpty()) {
                收集构造器(类, new 构造器声明(List.of(), 类.名, List.of(), List.of(),
                        new 语法树.块(List.of())));
            }
        } finally {
            当前类 = 旧当前类;
            类型参数名.clear();
            类型参数名.addAll(旧参数);
        }
    }

    private void 收集记录分量(类符号 类, 类型声明 声明) {
        for (参数 参数 : 声明.分量()) {
            if (查找字段(类, 参数.名()) != null) {
                失败("记录「" + 类.名 + "」的分量「" + 参数.名() + "」重复声明。");
            }
            类.字段.add(new 字段符号(转类型(参数.类型()), 参数.名(), 类.名));
        }
    }

    private void 收集记录方法(类符号 类) {
        List<中间代码.参数> 参数列表 = new ArrayList<>();
        for (字段符号 字段 : 类.字段) {
            参数列表.add(new 中间代码.参数(字段.类型, 字段.名));
        }
        List<中间代码.语句> 赋值 = new ArrayList<>();
        for (字段符号 字段 : 类.字段) {
            赋值.add(new 中间代码.表达式语句(new 中间代码.赋值(字段.类型,
                    new 中间代码.字段读(字段.类型, new 中间代码.变量读(类.类型, "这"), 字段.名),
                    new 中间代码.变量读(字段.类型, 字段.名))));
        }
        方法符号 构造器 = new 方法符号(类, "<构造>", false, 类型.无, 参数列表, null);
        构造器.是构造器 = true;
        构造器.中间 = new 中间代码.方法("<构造>", false, 类型.无, 参数列表,
                new 中间代码.块(赋值));
        类.构造器.add(构造器);
        for (字段符号 字段 : 类.字段) {
            类.方法.add(new 方法符号(类, 字段.名, false, 字段.类型, List.of(),
                    new 语法树.块(List.of(new 语法树.返回语句(
                            new 语法树.标识符(字段.名))))));
        }
        if (类.方法.stream().noneMatch(项 -> 项.名.equals("转文本"))) {
            类.方法.add(记录转文本(类));
        }
        if (类.方法.stream().noneMatch(项 -> 项.名.equals("等于"))) {
            类.方法.add(记录等于(类));
        }
        if (类.方法.stream().noneMatch(项 -> 项.名.equals("哈希码"))) {
            类.方法.add(记录哈希码(类));
        }
    }

    private 方法符号 记录转文本(类符号 类) {
        String 前缀 = "\"" + 简短记录名(类.名) + "[\"";
        中间代码.表达式 文本 = new 中间代码.常量(类型.文本, 前缀);
        boolean 首 = true;
        for (字段符号 字段 : 类.字段) {
            if (!首) {
                文本 = new 中间代码.二元(类型.文本, "+", 文本,
                        new 中间代码.常量(类型.文本, "\", \""));
            }
            首 = false;
            文本 = new 中间代码.二元(类型.文本, "+", 文本,
                    new 中间代码.常量(类型.文本, "\"" + 字段.名 + "=\""));
            文本 = new 中间代码.二元(类型.文本, "+", 文本,
                    内建(类型.文本, "值转文本", null, List.of(
                            new 中间代码.字段读(字段.类型,
                                    new 中间代码.变量读(类.类型, "这"), 字段.名))));
        }
        文本 = new 中间代码.二元(类型.文本, "+", 文本,
                new 中间代码.常量(类型.文本, "\"]\""));
        方法符号 方法 = new 方法符号(类, "转文本", false, 类型.文本, List.of(),
                new 语法树.块(List.of(new 语法树.返回语句(new 语法树.字面量("\"\"", "文本")))));
        方法.中间 = new 中间代码.方法("转文本", false, 类型.文本, List.of(),
                new 中间代码.返回语句(文本));
        return 方法;
    }

    private 方法符号 记录等于(类符号 类) {
        类型 对象类型 = 类型.类类型("对象");
        List<中间代码.语句> 语句 = new ArrayList<>();
        语句.add(new 中间代码.若语句(
                new 中间代码.二元(类型.布尔, "==",
                        new 中间代码.变量读(类.类型, "这"),
                        new 中间代码.变量读(对象类型, "其它")),
                new 中间代码.返回语句(new 中间代码.常量(类型.布尔, "真")), null));
        语句.add(new 中间代码.若语句(
                new 中间代码.一元(类型.布尔, "!",
                        new 中间代码.实例判断(类型.布尔,
                                new 中间代码.变量读(对象类型, "其它"), 类.名, null)),
                new 中间代码.返回语句(new 中间代码.常量(类型.布尔, "假")), null));
        String 另名 = "__另";
        语句.add(new 中间代码.局部变量语句(类.类型, 另名,
                new 中间代码.强制转换(类.类型, new 中间代码.变量读(对象类型, "其它"))));
        中间代码.表达式 条件 = null;
        for (字段符号 字段 : 类.字段) {
            中间代码.表达式 左 = new 中间代码.字段读(字段.类型,
                    new 中间代码.变量读(类.类型, "这"), 字段.名);
            中间代码.表达式 右 = new 中间代码.字段读(字段.类型,
                    new 中间代码.变量读(类.类型, 另名), 字段.名);
            中间代码.表达式 相等 = 内建(类型.布尔, "值相等", null, List.of(左, 右));
            条件 = 条件 == null ? 相等
                    : new 中间代码.二元(类型.布尔, "&&", 条件, 相等);
        }
        if (条件 == null) {
            条件 = new 中间代码.常量(类型.布尔, "真");
        }
        语句.add(new 中间代码.返回语句(条件));
        方法符号 方法 = new 方法符号(类, "等于", false, 类型.布尔,
                List.of(new 中间代码.参数(对象类型, "其它")), null);
        方法.中间 = new 中间代码.方法("等于", false, 类型.布尔,
                List.of(new 中间代码.参数(对象类型, "其它")), new 中间代码.块(语句));
        return 方法;
    }

    private 方法符号 记录哈希码(类符号 类) {
        中间代码.表达式 结果 = new 中间代码.常量(类型.整数, "0");
        for (字段符号 字段 : 类.字段) {
            结果 = new 中间代码.二元(类型.整数, "+",
                    new 中间代码.二元(类型.整数, "*",
                            new 中间代码.常量(类型.整数, "31"), 结果),
                    内建(类型.整数, "值哈希码", null, List.of(
                            new 中间代码.字段读(字段.类型,
                                    new 中间代码.变量读(类.类型, "这"), 字段.名))));
        }
        方法符号 方法 = new 方法符号(类, "哈希码", false, 类型.整数, List.of(), null);
        方法.中间 = new 中间代码.方法("哈希码", false, 类型.整数, List.of(),
                new 中间代码.返回语句(结果));
        return 方法;
    }

    private static String 简短记录名(String 名) {
        int 位置 = 名.lastIndexOf('$');
        return 位置 < 0 ? 名 : 名.substring(位置 + 1);
    }

    private void 收集字段(类符号 类, 字段声明 字段) {
        boolean 静态 = 类.是接口 || 字段.修饰符().contains("static");
        for (变量声明 变量 : 字段.变量()) {
            if (静态) {
                if (查找静态字段(类, 变量.名()) != null) {
                    失败("类「" + 类.名 + "」中静态字段「" + 变量.名() + "」重复声明。");
                }
                类.静态字段.add(new 静态字段符号(转类型(变量.类型()), 变量.名(), 类.名,
                        变量.初值()));
                continue;
            }
            if (查找字段(类, 变量.名()) != null) {
                失败("类「" + 类.名 + "」中字段「" + 变量.名() + "」重复声明。");
            }
            字段符号 符号 = new 字段符号(转类型(变量.类型()), 变量.名(), 类.名);
            符号.初值 = 变量.初值();
            类.字段.add(符号);
        }
    }

    private void 收集方法(类符号 类, 方法声明 方法) {
        if (方法.体() == null && !类.抽象 && !类.是接口) {
            失败("类「" + 类.名 + "」的方法「" + 方法.名() + "」没有方法体；请把类声明为抽象。");
        }
        java.util.Set<String> 旧参数 = new java.util.HashSet<>(类型参数名);
        for (类型参数 参数 : 方法.类型参数()) {
            类型参数名.add(参数.名());
        }
        try {
            List<中间代码.参数> 参数列表 = new ArrayList<>();
            for (参数 参数 : 方法.参数()) {
                if (参数.可变参数()) {
                    不支持("可变参数");
                }
                参数列表.add(new 中间代码.参数(转类型(参数.类型()), 参数.名()));
            }
            方法符号 符号 = new 方法符号(类, 方法.名(),
                    方法.修饰符().contains("static"), 转类型(方法.返回类型()), 参数列表,
                    方法.体());
            for (类型参数 参数 : 方法.类型参数()) {
                符号.类型参数名.add(参数.名());
            }
            类.方法.add(符号);
        } finally {
            类型参数名.clear();
            类型参数名.addAll(旧参数);
        }
    }

    private void 收集构造器(类符号 类, 构造器声明 构造器) {
        if (类.是接口) {
            失败("接口「" + 类.名 + "」不能声明构造器。");
        }
        List<中间代码.参数> 参数列表 = new ArrayList<>();
        if (类.外部 != null && !类.静态嵌套) {
            参数列表.add(new 中间代码.参数(类.外部.类型, "__外部"));
        }
        for (参数 参数 : 构造器.参数()) {
            if (参数.可变参数()) {
                不支持("可变参数");
            }
            参数列表.add(new 中间代码.参数(转类型(参数.类型()), 参数.名()));
        }
        方法符号 符号 = new 方法符号(类, 构造器.名(), false, 类型.无, 参数列表,
                构造器.体());
        符号.是构造器 = true;
        类.构造器.add(符号);
    }

