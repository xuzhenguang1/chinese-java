    private 中间代码.语句 分析语句(语法树.语句 语句) {
        中间代码.语句 结果 = 分析语句核心(语句);
        if (结果 != null) {
            Integer 行 = 语句 == null ? null : 源行号.get(语句);
            if (行 != null && 行 > 0) {
                当前行 = 行;
            }
            位置.记录(结果, 当前行);
        }
        return 结果;
    }

    private 中间代码.语句 分析语句核心(语法树.语句 语句) {
        if (语句 == null) {
            return new 中间代码.块(List.of());
        }
        if (语句 instanceof 语法树.块 x) {
            推入();
            try {
                List<中间代码.语句> 列表 = new ArrayList<>();
                for (语法树.语句 项 : x.语句()) {
                    列表.add(分析语句(项));
                }
                return new 中间代码.块(列表);
            } finally {
                弹出();
            }
        }
        if (语句 instanceof 局部变量语句 x) {
            return 分析局部变量(x.声明());
        }
        if (语句 instanceof 语法树.表达式语句 x) {
            return new 中间代码.表达式语句(分析表达式(x.值()));
        }
        if (语句 instanceof 语法树.返回语句 x) {
            return 分析返回(x);
        }
        if (语句 instanceof 语法树.若语句 x) {
            return 分析若语句(x);
        }
        if (语句 instanceof 语法树.对于语句 x) {
            return 分析对于(x);
        }
        if (语句 instanceof 语法树.增强对于 x) {
            return 分析增强对于(x);
        }
        if (语句 instanceof 语法树.当语句 x) {
            return new 中间代码.当语句(分析条件(x.条件()), 分析语句(x.体()));
        }
        if (语句 instanceof 语法树.做当语句 x) {
            中间代码.语句 体 = 分析语句(x.体());
            return new 中间代码.做当语句(体, 分析条件(x.条件()));
        }
        if (语句 instanceof 语法树.重复语句 x) {
            return 分析重复(x);
        }
        if (语句 instanceof 语法树.切换语句 x) {
            return 分析切换语句(x);
        }
        if (语句 instanceof 语法树.跳出语句 x) {
            if (x.标签() != null) {
                不支持("带标签的「跳出」");
            }
            return new 中间代码.跳出语句();
        }
        if (语句 instanceof 语法树.继续语句 x) {
            if (x.标签() != null) {
                不支持("带标签的「继续」");
            }
            return new 中间代码.继续语句();
        }
        if (语句 instanceof 语法树.空语句) {
            return new 中间代码.块(List.of());
        }
        if (语句 instanceof 语法树.尝试语句 x) {
            return 分析尝试(x);
        }
        if (语句 instanceof 语法树.抛出语句 x) {
            中间代码.表达式 值 = 分析表达式(x.值());
            类型 值类型 = 类型(值);
            if (!值类型.是类() || !是子类型(值类型.类名, "异常")) {
                失败("只能抛出「异常」及其子类的对象，实际是「" + 值类型.文本() + "」。");
            }
            return new 中间代码.抛出语句(值);
        }
        if (语句 instanceof 语法树.产出语句) {
            不支持("产出（yield）");
        }
        不支持("语句 " + 语句.getClass().getSimpleName());
        return null;
    }

    private 中间代码.语句 分析若语句(语法树.若语句 x) {
        if (x.条件() instanceof 语法树.实例判断 判断 && 判断.绑定名() != null) {
            类型 目标 = 转类型(判断.类型());
            中间代码.表达式 值 = 分析表达式(判断.左());
            类型 来源 = 类型(值);
            if (!目标.是类()) {
                失败("「是」后面的绑定类型必须是类。");
            }
            String 临时 = 临时变量("__是");
            推入();
            try {
                定义(临时, 来源);
                定义(判断.绑定名(), 目标);
                中间代码.表达式 判定 = new 中间代码.实例判断(类型.布尔,
                        new 中间代码.变量读(来源, 临时), 目标.类名, null);
                中间代码.表达式 绑定值 = new 中间代码.三目(目标, 判定,
                        new 中间代码.强制转换(目标, new 中间代码.变量读(来源, 临时)),
                        new 中间代码.常量(类型.空, "空"));
                中间代码.语句 成立 = 分析语句(x.成立());
                中间代码.语句 否则 = x.否则() == null ? null : 分析语句(x.否则());
                return new 中间代码.块(List.of(
                        new 中间代码.局部变量语句(来源, 临时, 值),
                        new 中间代码.局部变量语句(目标, 判断.绑定名(), 绑定值),
                        new 中间代码.若语句(判定, 成立, 否则)));
            } finally {
                弹出();
            }
        }
        return new 中间代码.若语句(分析条件(x.条件()), 分析语句(x.成立()),
                x.否则() == null ? null : 分析语句(x.否则()));
    }

    private 中间代码.语句 分析尝试(语法树.尝试语句 x) {
        中间代码.语句 体 = 分析语句(x.尝试块());
        List<中间代码.捕获子句> 捕获 = new ArrayList<>();
        for (语法树.捕获子句 项 : x.捕获()) {
            类型 异常类型 = 转类型(项.类型());
            if (!异常类型.是类() || !是子类型(异常类型.类名, "异常")) {
                失败("「捕获」的类型必须是「异常」及其子类，实际是「"
                        + 异常类型.文本() + "」。");
            }
            推入();
            try {
                定义(项.名(), 异常类型);
                捕获.add(new 中间代码.捕获子句(异常类型.类名, 项.名(),
                        分析语句(项.块())));
            } finally {
                弹出();
            }
        }
        中间代码.语句 兜底 = x.兜底() == null ? null : 分析语句(x.兜底());
        return new 中间代码.尝试语句(体, 捕获, 兜底);
    }

    private 中间代码.语句 分析局部变量(变量声明 声明) {
        类型 声明类型 = 转类型(声明.类型());
        中间代码.表达式 初值;
        if (声明.初值() instanceof 语法树.数组初始化 初始化) {
            初值 = 分析数组初始化(声明类型, 初始化);
        } else if (声明.初值() == null) {
            失败("局部变量「" + 声明.名() + "」缺少初值。");
            return null;
        } else {
            初值 = 分析表达式(声明.初值());
        }
        if (!可赋值(声明类型, 类型(初值))) {
            失败("不能把「" + 类型(初值).文本() + "」赋给「" + 声明类型.文本()
                    + "」变量「" + 声明.名() + "」。");
        }
        定义(声明.名(), 声明类型);
        return new 中间代码.局部变量语句(声明类型, 声明.名(), 初值);
    }

    private 中间代码.语句 分析返回(语法树.返回语句 x) {
        类型 目标 = 当前方法.返回类型;
        if (x.值() == null) {
            if (!目标.同型(类型.无)) {
                失败("方法「" + 当前方法.名 + "」需要返回值。");
            }
            return new 中间代码.返回语句(null);
        }
        if (目标.同型(类型.无)) {
            失败("「无」方法不能返回值。");
        }
        中间代码.表达式 值 = 分析表达式(x.值());
        if (!可赋值(目标, 类型(值))) {
            失败("返回值类型「" + 类型(值).文本() + "」与方法返回类型「"
                    + 目标.文本() + "」不兼容。");
        }
        return new 中间代码.返回语句(值);
    }

    private 中间代码.语句 分析对于(语法树.对于语句 x) {
        推入();
        try {
            中间代码.语句 初始化 = x.初始化() == null ? null : 分析语句(x.初始化());
            中间代码.表达式 条件 = x.条件() == null ? null : 分析条件(x.条件());
            List<中间代码.表达式> 更新 = new ArrayList<>();
            for (语法树.表达式 项 : x.更新()) {
                更新.add(分析表达式(项));
            }
            return new 中间代码.对于语句(初始化, 条件, 更新, 分析语句(x.体()));
        } finally {
            弹出();
        }
    }

    private 中间代码.语句 分析增强对于(语法树.增强对于 x) {
        中间代码.表达式 可迭代 = 分析表达式(x.可迭代());
        类型 可迭代类型 = 类型(可迭代);
        类型 元素类型;
        中间代码.表达式 容器 = 可迭代;
        if (可迭代类型.是数组()) {
            元素类型 = 可迭代类型.元素;
        } else if (可迭代类型.是类()) {
            String 容器名 = 规范内置名(可迭代类型.类名);
            switch (容器名) {
                case "清单", "集" -> 元素类型 = 元素类型(可迭代类型, 0);
                case "键值表" -> {
                    类型 键类型 = 元素类型(可迭代类型, 0);
                    类型 键集类型 = 类型.类类型("集", List.of(键类型));
                    容器 = 内建(键集类型, "字典键集合", 可迭代, List.of());
                    可迭代类型 = 键集类型;
                    元素类型 = 键类型;
                }
                case "流" -> {
                    类型 流元素 = 元素类型(可迭代类型, 0);
                    类型 清单类型 = 类型.类类型("清单", List.of(流元素));
                    容器 = 内建(清单类型, "流收集清单", 可迭代,
                            List.of(内建(类型.类类型("收集器清单"), "收集器清单", null,
                                    List.of())));
                    可迭代类型 = 清单类型;
                    元素类型 = 流元素;
                }
                default -> {
                    不支持("增强 对于 遍历「" + 可迭代类型.文本() + "」");
                    return null;
                }
            }
        } else {
            不支持("增强 对于 遍历「" + 可迭代类型.文本() + "」");
            return null;
        }
        类型 变量类型 = x.变量().类型() == null ? 元素类型 : 转类型(x.变量().类型());
        if (!可赋值(变量类型, 元素类型)) {
            失败("循环变量类型「" + 变量类型.文本() + "」不能接收「"
                    + 元素类型.文本() + "」元素。");
        }
        String 容器名 = 临时变量("__容器");
        String 下标名 = 临时变量("__下标");
        boolean 数组 = 可迭代类型.是数组();
        推入();
        try {
            定义(x.变量().名(), 变量类型);
            定义(容器名, 可迭代类型);
            定义(下标名, 类型.整数);
            中间代码.语句 初始化 = new 中间代码.块(List.of(
                    new 中间代码.局部变量语句(可迭代类型, 容器名, 容器),
                    new 中间代码.局部变量语句(类型.整数, 下标名,
                            new 中间代码.常量(类型.整数, "0"))));
            中间代码.表达式 长度;
            if (数组) {
                长度 = new 中间代码.数组长度(类型.整数,
                        new 中间代码.变量读(可迭代类型, 容器名));
            } else {
                String 长度名 = 规范内置名(可迭代类型.类名).equals("集")
                        ? "集元素数" : "清单元素数";
                长度 = 内建(类型.整数, 长度名, new 中间代码.变量读(可迭代类型, 容器名),
                        List.of());
            }
            中间代码.表达式 条件 = new 中间代码.二元(类型.布尔, "<",
                    new 中间代码.变量读(类型.整数, 下标名), 长度);
            中间代码.表达式 更新 = new 中间代码.赋值(类型.整数,
                    new 中间代码.变量读(类型.整数, 下标名),
                    new 中间代码.二元(类型.整数, "+", new 中间代码.变量读(类型.整数, 下标名),
                            new 中间代码.常量(类型.整数, "1")));
            中间代码.表达式 元素;
            if (数组) {
                元素 = new 中间代码.数组读(元素类型, new 中间代码.变量读(可迭代类型, 容器名),
                        new 中间代码.变量读(类型.整数, 下标名));
            } else {
                String 取出名 = 规范内置名(可迭代类型.类名).equals("集")
                        ? "集取出" : "清单取出";
                元素 = 内建(元素类型, 取出名, new 中间代码.变量读(可迭代类型, 容器名),
                        List.of(new 中间代码.变量读(类型.整数, 下标名)));
            }
            中间代码.语句 体 = new 中间代码.块(List.of(
                    new 中间代码.局部变量语句(变量类型, x.变量().名(), 元素),
                    分析语句(x.体())));
            return new 中间代码.对于语句(初始化, 条件, List.of(更新), 体);
        } finally {
            弹出();
        }
    }

    private 中间代码.语句 分析重复(语法树.重复语句 x) {
        中间代码.表达式 次数 = 分析表达式(x.次数());
        if (!类型(次数).是整数族()) {
            失败("「重复 N 次」的次数必须是整数。");
        }
        String 名 = x.变量名();
        推入();
        try {
            定义(名, 类型.整数);
            中间代码.语句 体 = 分析语句(x.体());
            中间代码.语句 初始化 = new 中间代码.局部变量语句(类型.整数, 名,
                    new 中间代码.常量(类型.整数, "1"));
            中间代码.表达式 条件 = new 中间代码.二元(类型.布尔, "<=",
                    new 中间代码.变量读(类型.整数, 名), 次数);
            中间代码.表达式 更新 = new 中间代码.赋值(类型.整数,
                    new 中间代码.变量读(类型.整数, 名),
                    new 中间代码.二元(类型.整数, "+", new 中间代码.变量读(类型.整数, 名),
                            new 中间代码.常量(类型.整数, "1")));
            return new 中间代码.对于语句(初始化, 条件, List.of(更新), 体);
        } finally {
            弹出();
        }
    }

    private 中间代码.语句 分析切换语句(语法树.切换语句 x) {
        中间代码.表达式 选择子 = 分析表达式(x.选择子());
        类型 选择类型 = 类型(选择子);
        List<语法树.切换分支> 分支 = x.分支();
        List<中间代码.语句> 结果们 = new ArrayList<>();
        中间代码.语句 默认 = new 中间代码.块(List.of());
        for (语法树.切换分支 项 : 分支) {
            中间代码.语句 结果 = 分析语句(项.结果());
            结果们.add(结果);
            if (项.是默认()) {
                默认 = 结果;
            }
        }
        中间代码.语句 链 = 默认;
        for (int i = 分支.size() - 1; i >= 0; i--) {
            语法树.切换分支 项 = 分支.get(i);
            if (项.是默认()) {
                continue;
            }
            List<语法树.表达式> 情形 = 项.情形();
            for (int j = 情形.size() - 1; j >= 0; j--) {
                中间代码.表达式 值 = 分析表达式(情形.get(j));
                中间代码.表达式 条件 = 组装二元("==", 选择子, 选择类型, 值, 类型(值));
                链 = new 中间代码.若语句(条件, 结果们.get(i), 链);
            }
        }
        return 链;
    }

