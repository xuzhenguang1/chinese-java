    private List<中间代码.类定义> 生成() {
        List<中间代码.类定义> 类们 = new ArrayList<>();
        for (类符号 类 : 类表.values()) {
            if (类.隐式) {
                continue;
            }
            List<中间代码.字段定义> 字段 = new ArrayList<>();
            for (字段符号 项 : 类.字段) {
                字段.add(new 中间代码.字段定义(项.类型, 项.名));
            }
            List<中间代码.静态字段定义> 静态字段 = new ArrayList<>();
            for (静态字段符号 项 : 类.静态字段) {
                静态字段.add(new 中间代码.静态字段定义(项.类型, 项.名, 项.中间初值));
            }
            List<中间代码.枚举常量定义> 枚举常量 = new ArrayList<>();
            for (枚举常量符号 项 : 类.枚举常量) {
                枚举常量.add(new 中间代码.枚举常量定义(项.名, List.copyOf(项.中间实参)));
            }
            List<中间代码.方法> 构造器 = new ArrayList<>();
            for (方法符号 项 : 类.构造器) {
                if (项.中间 != null) {
                    构造器.add(项.中间);
                }
            }
            List<中间代码.方法> 方法 = new ArrayList<>();
            for (方法符号 项 : 类.方法) {
                if (项.中间 != null) {
                    方法.add(项.中间);
                } else if (项.抽象()) {
                    /* 抽象方法保留签名，供 M4 的虚调用槽与类型检查使用。 */
                    方法.add(new 中间代码.方法(项.名, 项.静态, 项.返回类型, 项.参数, null));
                }
            }
            if (类.枚举 && 方法.stream().noneMatch(项 -> 项.名().equals("转文本"))) {
                方法.add(new 中间代码.方法("转文本", false, 类型.文本, List.of(),
                        new 中间代码.返回语句(new 中间代码.字段读(类型.文本,
                                new 中间代码.变量读(类.类型, "这"), "__枚举名"))));
            }
            类们.add(new 中间代码.类定义(类.名, 字段, 构造器, 方法,
                    类.父类, List.copyOf(类.接口), 类.抽象, 类.枚举,
                    静态字段, 枚举常量));
        }
        return 类们;
    }

    private 类型 转类型(类型引用 引用) {
        if (引用 == null) {
            失败("缺少类型。");
        }
        String 名 = 引用.名();
        类型 基础;
        switch (名) {
            case "整数", "int" -> 基础 = 类型.整数;
            case "长整数", "long" -> 基础 = 类型.长整数;
            case "短整数", "short" -> 基础 = 类型.短整数;
            case "字节", "byte" -> 基础 = 类型.字节;
            case "浮点", "float" -> 基础 = 类型.浮点;
            case "双浮点", "double" -> 基础 = 类型.双浮点;
            case "字符", "char" -> 基础 = 类型.字符;
            case "布尔", "boolean" -> 基础 = 类型.布尔;
            case "无", "void" -> 基础 = 类型.无;
            case "字符串", "String", "文本" -> 基础 = 类型.文本;
            case "对象", "Object" -> 基础 = 类型.类类型("对象");
            default -> {
                if (类型参数名.contains(名)) {
                    基础 = 类型.类类型(泛型值名);
                } else if (是内置类型名(名)) {
                    基础 = 类型.类类型(规范内置名(名));
                } else if (类表.containsKey(名)) {
                    基础 = 类表.get(名).类型;
                } else {
                    String 扁平 = 查找类名(名);
                    if (类表.containsKey(扁平)) {
                        基础 = 类表.get(扁平).类型;
                    } else {
                        基础 = 类型.类类型(名);
                    }
                }
            }
        }
        if (!引用.实参().isEmpty()) {
            List<类型> 实参 = new ArrayList<>();
            for (类型引用 项 : 引用.实参()) {
                实参.add(转类型(项));
            }
            if (基础.是类()) {
                基础 = 类型.类类型(基础.类名, 实参);
            } else if (基础.同型(类型.文本)) {
                基础 = 类型.类类型("文本", 实参);
            }
        }
        for (int i = 0; i < 引用.数组维数(); i++) {
            基础 = 类型.数组(基础);
        }
        return 基础;
    }

