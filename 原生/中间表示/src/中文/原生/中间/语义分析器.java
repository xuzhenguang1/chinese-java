    private 中间代码.表达式 分析函数实参调用(语法树.调用 x) {
        String 名 = x.名();
        List<语法树.表达式> 源实参 = x.实参();
        if (x.接收者() instanceof 语法树.标识符 接收标识 && 查找变量(接收标识.名()) == null) {
            if (接收标识.名().equals("比较器") && 名.equals("按整数") && 源实参.size() == 1) {
                return 合成按整数(源实参.get(0));
            }
            if (接收标识.名().equals("并发")
                    && (名.equals("执行") || 名.equals("提交")) && 源实参.size() == 2) {
                中间代码.表达式 池 = 分析表达式(源实参.get(0));
                合成结果 任务 = 合成λ(源实参.get(1), List.of(),
                        名.equals("执行") ? 类型.无 : null);
                List<中间代码.表达式> 实参2 = List.of(池, 任务.表达式);
                List<类型> 类型2 = List.of(类型(池), 类型(任务.表达式));
                return 标准库内置("并发", 名, 实参2, 类型2);
            }
            失败("不支持对「" + 接收标识.名() + "." + 名 + "」传入 λ。");
        }
        中间代码.表达式 接收 = 分析表达式(x.接收者());
        类型 接收类型 = 类型(接收);
        String 类名 = 接收类型.是类() ? 接收类型.类名 : "";
        if (类名.equals("流")) {
            类型 元素 = 元素类型(接收类型, 0);
            if (名.equals("过滤")) {
                合成结果 结果 = 合成λ(源实参.get(0), List.of(元素), 类型.布尔);
                return 内建(类型.类类型("流", List.of(元素)), "流过滤", 接收,
                        List.of(结果.表达式));
            }
            if (名.equals("变换")) {
                合成结果 结果 = 合成λ(源实参.get(0), List.of(元素), null);
                return 内建(类型.类类型("流", List.of(结果.返回类型)), "流变换", 接收,
                        List.of(结果.表达式));
            }
            if (名.equals("遍历")) {
                合成结果 结果 = 合成λ(源实参.get(0), List.of(元素), 类型.无);
                return 内建(类型.无, "流遍历", 接收, List.of(结果.表达式));
            }
        }
        if (类名.equals("键值表") && 名.equals("遍历")) {
            合成结果 结果 = 合成λ(源实参.get(0),
                    List.of(元素类型(接收类型, 0), 元素类型(接收类型, 1)), 类型.无);
            return 内建(类型.无, "字典遍历", 接收, List.of(结果.表达式));
        }
        if (类名.equals("可选值") && 名.equals("存在时")) {
            合成结果 结果 = 合成λ(源实参.get(0), List.of(元素类型(接收类型, 0)), 类型.无);
            return 内建(类型.无, "可选值存在时", 接收, List.of(结果.表达式));
        }
        失败("内置类型「" + 接收类型.文本() + "」不支持方法「" + 名 + "」接收 λ。");
        return null;
    }

    private 合成结果 合成λ(语法树.表达式 源, List<类型> 形参类型, 类型 期望返回) {
        if (!(源 instanceof 语法树.λ表达式 λ)) {
            失败("此处需要 λ 表达式。");
            return null;
        }
        if (λ.参数().size() != 形参类型.size()) {
            失败("λ 参数个数不匹配：需要 " + 形参类型.size() + " 个。");
        }
        String 名 = "__λ" + (++合成序号);
        类符号 类 = new 类符号(名);
        类.合成 = true;
        List<捕获变量> 捕获 = 收集捕获();
        for (捕获变量 项 : 捕获) {
            类.字段.add(new 字段符号(项.类型, 项.名, 名));
        }
        List<中间代码.参数> 捕获参数 = new ArrayList<>();
        List<中间代码.语句> 赋值 = new ArrayList<>();
        for (捕获变量 项 : 捕获) {
            捕获参数.add(new 中间代码.参数(项.类型, 项.名));
            赋值.add(new 中间代码.表达式语句(new 中间代码.赋值(项.类型,
                    new 中间代码.字段读(项.类型, new 中间代码.变量读(类.类型, "这"), 项.名),
                    new 中间代码.变量读(项.类型, 项.名))));
        }
        方法符号 构造器 = new 方法符号(类, "<构造>", false, 类型.无, 捕获参数, null);
        构造器.是构造器 = true;
        构造器.中间 = new 中间代码.方法("<构造>", false, 类型.无, 捕获参数,
                new 中间代码.块(赋值));
        类.构造器.add(构造器);

        类型 返回 = 期望返回 == null ? 类型.类类型(泛型值名) : 期望返回;
        List<中间代码.参数> 形参 = new ArrayList<>();
        for (int i = 0; i < 形参类型.size(); i++) {
            形参.add(new 中间代码.参数(形参类型.get(i), λ.参数().get(i).名()));
        }
        语法树.语句 体 = λ.体();
        if (体 instanceof 语法树.表达式语句 表达式体) {
            体 = 返回.equals(类型.无) ? 表达式体
                    : new 语法树.返回语句(表达式体.值());
        }
        方法符号 方法 = new 方法符号(类, "调用", false, 返回, 形参, 体);
        方法.中间 = 分析方法(类, 方法);
        类.方法.add(方法);
        类表.put(名, 类);
        List<中间代码.表达式> 捕获值 = new ArrayList<>();
        for (捕获变量 项 : 捕获) {
            捕获值.add(new 中间代码.变量读(项.类型, 项.名));
        }
        return new 合成结果(new 中间代码.新建对象(类.类型, 名, 捕获值), 返回);
    }

    private 合成结果 合成方法引用(语法树.方法引用 源) {
        语法树.标识符 接收标识;
        if (源.接收者() instanceof 语法树.标识符 标识) {
            接收标识 = 标识;
        } else {
            失败("只支持「类::方法」形式的方法引用。");
            return null;
        }
        类符号 目标类 = 解析类(接收标识.名());
        if (目标类 == null) {
            失败("未知类「" + 接收标识.名() + "」。");
        }
        方法符号 目标 = null;
        for (方法符号 方法 : 目标类.方法) {
            if (方法.名.equals(源.名()) && 方法.参数.isEmpty()) {
                目标 = 方法;
                break;
            }
        }
        if (目标 == null) {
            失败("类「" + 目标类.名 + "」没有无参方法「" + 源.名() + "」。");
        }
        String 名 = "__方法引用" + (++合成序号);
        类符号 类 = new 类符号(名);
        类.合成 = true;
        方法符号 构造器 = new 方法符号(类, "<构造>", false, 类型.无, List.of(), null);
        构造器.是构造器 = true;
        构造器.中间 = new 中间代码.方法("<构造>", false, 类型.无, List.of(),
                new 中间代码.块(List.of()));
        类.构造器.add(构造器);
        类型 参数类型 = 目标类.类型;
        中间代码.参数 参数 = new 中间代码.参数(参数类型, "参数");
        中间代码.方法 中间 = new 中间代码.方法("调用", false, 目标.返回类型,
                List.of(参数),
                new 中间代码.返回语句(new 中间代码.调用(目标.返回类型,
                        中间代码.分派.实例, 目标.所属.名, 目标.名,
                        new 中间代码.变量读(参数类型, "参数"), List.of())));
        方法符号 方法 = new 方法符号(类, "调用", false, 目标.返回类型, List.of(参数), null);
        方法.中间 = 中间;
        类.方法.add(方法);
        类表.put(名, 类);
        return new 合成结果(new 中间代码.新建对象(类.类型, 名, List.of()), 目标.返回类型);
    }

    private List<捕获变量> 收集捕获() {
        List<捕获变量> 结果 = new ArrayList<>();
        java.util.Set<String> 已见 = new java.util.HashSet<>();
        for (Map<String, 类型> 层 : 作用域) {
            for (Map.Entry<String, 类型> 项 : 层.entrySet()) {
                if (项.getKey().equals("这") || 项.getKey().equals("父")) {
                    continue;
                }
                if (已见.add(项.getKey())) {
                    结果.add(new 捕获变量(项.getKey(), 项.getValue()));
                }
            }
        }
        return 结果;
    }

