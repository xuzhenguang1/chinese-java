    private List<中间代码.类定义> 生成() {
        List<中间代码.类定义> 类们 = new ArrayList<>();
        for (类符号 类 : 类表.values()) {
            List<中间代码.字段定义> 字段 = new ArrayList<>();
            for (字段符号 项 : 类.字段) {
                字段.add(new 中间代码.字段定义(项.类型, 项.名));
            }
            List<中间代码.方法> 构造器 = new ArrayList<>();
            for (方法符号 项 : 类.构造器) {
                if (项.中间 != null) {
                    构造器.add(项.中间);
                }
            }
            List<中间代码.方法> 方法 = new ArrayList<>();
            for (方法符号 项 : 类.方法) {
                if (项.中间 != null) {
                    方法.add(项.中间);
                }
            }
            类们.add(new 中间代码.类定义(类.名, 字段, 构造器, 方法));
        }
        return 类们;
    }

    private 类型 转类型(类型引用 引用) {
        if (引用 == null) {
            失败("缺少类型。");
        }
        String 名 = 引用.名();
        类型 基础;
        switch (名) {
            case "整数", "int" -> 基础 = 类型.整数;
            case "长整数", "long" -> 基础 = 类型.长整数;
            case "短整数", "short" -> 基础 = 类型.短整数;
            case "字节", "byte" -> 基础 = 类型.字节;
            case "浮点", "float" -> 基础 = 类型.浮点;
            case "双浮点", "double" -> 基础 = 类型.双浮点;
            case "字符", "char" -> 基础 = 类型.字符;
            case "布尔", "boolean" -> 基础 = 类型.布尔;
            case "无", "void" -> 基础 = 类型.无;
            case "字符串", "String" -> 基础 = 类型.文本;
            default -> {
                if (词表.是类型别名(名)) {
                    不支持("类型「" + 名 + "」");
                }
                基础 = 类型.类类型(名);
            }
        }
        if (!引用.实参().isEmpty()) {
            不支持("泛型类型「" + 名 + "」");
        }
        for (int i = 0; i < 引用.数组维数(); i++) {
            基础 = 类型.数组(基础);
        }
        return 基础;
    }

    private 类型 类型(中间代码.表达式 值) {
        if (值 instanceof 中间代码.常量 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.变量读 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.字段读 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.数组读 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.数组长度 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.二元 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.一元 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.三目 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.强制转换 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.赋值 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.调用 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.新建对象 x) {
            return x.类型();
        }
        if (值 instanceof 中间代码.新建数组 x) {
            return x.类型();
        }
        失败("内部错误：表达式没有类型。");
        return 类型.错误;
    }

    private 中间代码.表达式 分析条件(语法树.表达式 x) {
        中间代码.表达式 条件 = 分析表达式(x);
        if (!类型(条件).同型(类型.布尔)) {
            失败("条件必须是布尔表达式。");
        }
        return 条件;
    }

    private 字段符号 查找字段(类符号 类, String 名) {
        if (类 == null) {
            return null;
        }
        for (字段符号 字段 : 类.字段) {
            if (字段.名.equals(名)) {
                return 字段;
            }
        }
        return null;
    }

