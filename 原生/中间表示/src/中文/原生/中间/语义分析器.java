    private 方法符号 选方法(类符号 类, String 名, List<类型> 实参类型) {
        方法符号 最佳 = null;
        int 最佳分 = Integer.MAX_VALUE;
        for (方法符号 方法 : 类.方法) {
            if (!方法.名.equals(名) || 方法.参数.size() != 实参类型.size()) {
                continue;
            }
            int 分 = 匹配分(方法.参数, 实参类型);
            if (分 >= 0 && 分 < 最佳分) {
                最佳 = 方法;
                最佳分 = 分;
            }
        }
        return 最佳;
    }

    private 方法符号 选构造器(类符号 类, List<类型> 实参类型) {
        方法符号 最佳 = null;
        int 最佳分 = Integer.MAX_VALUE;
        for (方法符号 构造器 : 类.构造器) {
            if (构造器.参数.size() != 实参类型.size()) {
                continue;
            }
            int 分 = 匹配分(构造器.参数, 实参类型);
            if (分 >= 0 && 分 < 最佳分) {
                最佳 = 构造器;
                最佳分 = 分;
            }
        }
        return 最佳;
    }

    private int 匹配分(List<中间代码.参数> 形参, List<类型> 实参) {
        int 总分 = 0;
        for (int i = 0; i < 形参.size(); i++) {
            类型 形 = 形参.get(i).类型();
            类型 实 = 实参.get(i);
            if (形.同型(实)) {
                continue;
            }
            if (可赋值(形, 实)) {
                总分++;
                continue;
            }
            return -1;
        }
        return 总分;
    }

