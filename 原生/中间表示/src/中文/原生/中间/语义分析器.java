    /** 提交任务的结果类型：λ 的「调用」返回类型；推断不出时按对象处理。 */
    private 类型 任务返回类型(类型 任务) {
        if (任务 != null && 任务.是类()) {
            类符号 类 = 类表.get(任务.类名);
            if (类 != null) {
                for (方法符号 方法 : 类.方法) {
                    if (方法.名.equals("调用") && !方法.静态) {
                        if (方法.返回类型.是类() && 泛型值名.equals(方法.返回类型.类名)
                                && 方法.中间 != null) {
                            if (方法.中间.体() instanceof 中间代码.返回语句 返回) {
                                return 类型(返回.值());
                            }
                            if (方法.中间.体() instanceof 中间代码.块 块) {
                                for (中间代码.语句 项 : 块.语句()) {
                                    if (项 instanceof 中间代码.返回语句 返回) {
                                        return 类型(返回.值());
                                    }
                                }
                            }
                        }
                        return 方法.返回类型;
                    }
                }
            }
        }
        return 类型.类类型("对象");
    }

