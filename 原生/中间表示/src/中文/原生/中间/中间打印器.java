package 中文.原生.中间;

import java.util.List;

/** MIR 确定性文本输出：两空格缩进，供快照与人工检查。 */
public final class 中间打印器 {

    private final StringBuilder 输出 = new StringBuilder();

    public static String 打印(中间代码.程序 程序) {
        中间打印器 打印器 = new 中间打印器();
        打印器.行(0, "程序");
        for (中间代码.类定义 类 : 程序.类()) {
            打印器.类(类);
        }
        return 打印器.输出.toString();
    }

    private void 类(中间代码.类定义 类) {
        StringBuilder 头 = new StringBuilder("类 ").append(类.名());
        if (类.抽象()) {
            头.append(" 抽象");
        }
        if (类.枚举()) {
            头.append(" 枚举");
        }
        if (类.父类() != null) {
            头.append(" 父 ").append(类.父类());
        }
        if (!类.接口().isEmpty()) {
            头.append(" 实现 ").append(String.join(",", 类.接口()));
        }
        行(1, 头.toString());
        for (中间代码.字段定义 字段 : 类.字段()) {
            行(2, "字段 " + 字段.类型().文本() + " " + 字段.名());
        }
        for (中间代码.静态字段定义 字段 : 类.静态字段()) {
            行(2, "静态字段 " + 字段.类型().文本() + " " + 字段.名());
            if (字段.初值() != null) {
                行(3, "初值");
                表达式(字段.初值(), 4);
            }
        }
        for (中间代码.枚举常量定义 常量 : 类.枚举常量()) {
            行(2, "枚举常量 " + 常量.名());
            for (中间代码.表达式 项 : 常量.实参()) {
                表达式(项, 3);
            }
        }
        for (中间代码.方法 构造器 : 类.构造器()) {
            行(2, "构造器 " + 构造器.名());
            参数(构造器.参数(), 3);
            语句(构造器.体(), 3);
        }
        for (中间代码.方法 方法 : 类.方法()) {
            行(2, "方法 " + 方法.名() + (方法.静态() ? " 静态 " : " 实例 ")
                    + 方法.返回类型().文本());
            参数(方法.参数(), 3);
            语句(方法.体(), 3);
        }
    }

    private void 参数(List<中间代码.参数> 参数, int 层级) {
        for (中间代码.参数 项 : 参数) {
            行(层级, "参数 " + 项.类型().文本() + " " + 项.名());
        }
    }

    private void 语句(中间代码.语句 语句, int 层级) {
        if (语句 == null) {
            行(层级, "空语句");
            return;
        }
        if (语句 instanceof 中间代码.块 x) {
            行(层级, "块");
            for (中间代码.语句 项 : x.语句()) {
                语句(项, 层级 + 1);
            }
            return;
        }
        if (语句 instanceof 中间代码.局部变量语句 x) {
            行(层级, "变量 " + x.类型().文本() + " " + x.名());
            表达式(x.初值(), 层级 + 1);
            return;
        }
        if (语句 instanceof 中间代码.表达式语句 x) {
            行(层级, "表达式语句");
            表达式(x.值(), 层级 + 1);
            return;
        }
        if (语句 instanceof 中间代码.返回语句 x) {
            行(层级, "返回");
            if (x.值() != null) {
                表达式(x.值(), 层级 + 1);
            }
            return;
        }
        if (语句 instanceof 中间代码.若语句 x) {
            行(层级, "若");
            行(层级 + 1, "条件");
            表达式(x.条件(), 层级 + 2);
            行(层级 + 1, "则");
            语句(x.成立(), 层级 + 2);
            if (x.否则() != null) {
                行(层级 + 1, "否则");
                语句(x.否则(), 层级 + 2);
            }
            return;
        }
        if (语句 instanceof 中间代码.对于语句 x) {
            行(层级, "对于");
            行(层级 + 1, "初始化");
            if (x.初始化() == null) {
                行(层级 + 2, "空语句");
            } else {
                语句(x.初始化(), 层级 + 2);
            }
            行(层级 + 1, "条件");
            if (x.条件() == null) {
                行(层级 + 2, "真");
            } else {
                表达式(x.条件(), 层级 + 2);
            }
            行(层级 + 1, "更新");
            for (中间代码.表达式 项 : x.更新()) {
                表达式(项, 层级 + 2);
            }
            行(层级 + 1, "体");
            语句(x.体(), 层级 + 2);
            return;
        }
        if (语句 instanceof 中间代码.当语句 x) {
            行(层级, "当");
            行(层级 + 1, "条件");
            表达式(x.条件(), 层级 + 2);
            行(层级 + 1, "体");
            语句(x.体(), 层级 + 2);
            return;
        }
        if (语句 instanceof 中间代码.做当语句 x) {
            行(层级, "做当");
            行(层级 + 1, "体");
            语句(x.体(), 层级 + 2);
            行(层级 + 1, "条件");
            表达式(x.条件(), 层级 + 2);
            return;
        }
        if (语句 instanceof 中间代码.跳出语句) {
            行(层级, "跳出");
            return;
        }
        if (语句 instanceof 中间代码.继续语句) {
            行(层级, "继续");
            return;
        }
        if (语句 instanceof 中间代码.尝试语句 x) {
            行(层级, "尝试");
            语句(x.体(), 层级 + 1);
            for (中间代码.捕获子句 捕获 : x.捕获()) {
                行(层级, "捕获 " + 捕获.类名() + " " + 捕获.变量名());
                语句(捕获.体(), 层级 + 1);
            }
            if (x.兜底() != null) {
                行(层级, "兜底");
                语句(x.兜底(), 层级 + 1);
            }
            return;
        }
        if (语句 instanceof 中间代码.抛出语句 x) {
            行(层级, "抛出");
            表达式(x.值(), 层级 + 1);
            return;
        }
        行(层级, "未知语句 " + 语句.getClass().getSimpleName());
    }

    private void 表达式(中间代码.表达式 表达式, int 层级) {
        if (表达式 instanceof 中间代码.常量 x) {
            行(层级, "常量 " + x.类型().文本() + " " + x.原文());
            return;
        }
        if (表达式 instanceof 中间代码.变量读 x) {
            行(层级, "变量读 " + x.类型().文本() + " " + x.名());
            return;
        }
        if (表达式 instanceof 中间代码.字段读 x) {
            行(层级, "字段读 " + x.类型().文本() + " " + x.名());
            行(层级 + 1, "接收者");
            表达式(x.接收者(), 层级 + 2);
            return;
        }
        if (表达式 instanceof 中间代码.数组读 x) {
            行(层级, "数组读 " + x.类型().文本());
            行(层级 + 1, "数组");
            表达式(x.数组(), 层级 + 2);
            行(层级 + 1, "下标");
            表达式(x.下标(), 层级 + 2);
            return;
        }
        if (表达式 instanceof 中间代码.数组长度 x) {
            行(层级, "数组长度 " + x.类型().文本());
            表达式(x.数组(), 层级 + 1);
            return;
        }
        if (表达式 instanceof 中间代码.二元 x) {
            行(层级, "二元 " + x.类型().文本() + " " + x.运算符());
            表达式(x.左(), 层级 + 1);
            表达式(x.右(), 层级 + 1);
            return;
        }
        if (表达式 instanceof 中间代码.一元 x) {
            行(层级, "一元 " + x.类型().文本() + " " + x.运算符());
            表达式(x.操作数(), 层级 + 1);
            return;
        }
        if (表达式 instanceof 中间代码.三目 x) {
            行(层级, "三目 " + x.类型().文本());
            行(层级 + 1, "条件");
            表达式(x.条件(), 层级 + 2);
            行(层级 + 1, "真");
            表达式(x.真(), 层级 + 2);
            行(层级 + 1, "假");
            表达式(x.假(), 层级 + 2);
            return;
        }
        if (表达式 instanceof 中间代码.强制转换 x) {
            行(层级, "强制转换 " + x.类型().文本());
            表达式(x.操作数(), 层级 + 1);
            return;
        }
        if (表达式 instanceof 中间代码.赋值 x) {
            行(层级, "赋值 " + x.类型().文本());
            表达式(x.左(), 层级 + 1);
            表达式(x.右(), 层级 + 1);
            return;
        }
        if (表达式 instanceof 中间代码.调用 x) {
            行(层级, "调用 " + x.分派().name() + " " + x.名());
            if (x.接收者() != null) {
                行(层级 + 1, "接收者");
                表达式(x.接收者(), 层级 + 2);
            }
            for (中间代码.表达式 项 : x.实参()) {
                表达式(项, 层级 + 1);
            }
            return;
        }
        if (表达式 instanceof 中间代码.新建对象 x) {
            行(层级, "新建对象 " + x.类型().文本() + " " + x.类名());
            for (中间代码.表达式 项 : x.实参()) {
                表达式(项, 层级 + 1);
            }
            return;
        }
        if (表达式 instanceof 中间代码.新建数组 x) {
            行(层级, "新建数组 " + x.类型().文本() + " 元素 " + x.元素类型().文本());
            行(层级 + 1, "长度");
            表达式(x.长度(), 层级 + 2);
            for (中间代码.表达式 项 : x.初值()) {
                行(层级 + 1, "初值");
                表达式(项, 层级 + 2);
            }
            return;
        }
        if (表达式 instanceof 中间代码.实例判断 x) {
            行(层级, "实例判断 " + x.类型().文本() + " " + x.目标类()
                    + (x.绑定名() == null ? "" : " " + x.绑定名()));
            表达式(x.值(), 层级 + 1);
            return;
        }
        if (表达式 instanceof 中间代码.静态字段读 x) {
            行(层级, "静态字段读 " + x.类型().文本() + " " + x.类名() + "." + x.名());
            return;
        }
        if (表达式 instanceof 中间代码.枚举常量读 x) {
            行(层级, "枚举常量读 " + x.类型().文本() + " " + x.枚举类() + "." + x.常量名());
            return;
        }
        if (表达式 instanceof 中间代码.枚举全部值 x) {
            行(层级, "枚举全部值 " + x.类型().文本() + " " + x.枚举类());
            return;
        }
        if (表达式 instanceof 中间代码.枚举按名取值 x) {
            行(层级, "枚举按名取值 " + x.类型().文本() + " " + x.枚举类());
            表达式(x.名(), 层级 + 1);
            return;
        }
        if (表达式 instanceof 中间代码.顺序表达式 x) {
            行(层级, "顺序表达式 " + x.类型().文本());
            for (中间代码.语句 项 : x.前奏()) {
                语句(项, 层级 + 1);
            }
            行(层级 + 1, "结果");
            表达式(x.结果(), 层级 + 2);
            return;
        }
        行(层级, "未知表达式 " + 表达式.getClass().getSimpleName());
    }

    private void 行(int 层级, String 文本) {
        输出.append("  ".repeat(层级)).append(文本).append('\n');
    }
}
