// 4.5 `数组清单.从(...)`：一行建出可变清单，之后仍可 加入 / 移除。
// 运行：.\工具\对话\运行.ps1 示例\可变清单工厂.java
清单<字符串> 名单 = 数组清单.从("甲", "乙");
名单.加入("丙");
打印行("元素数 {名单.元素数()}：{名单}");

// 空参数得到空清单
清单<整数> 空清单 = 数组清单.从();
空清单.加入(1);
打印行("空清单加入后 {空清单.元素数()} 个");

// 实参里嵌套普通调用
清单<字符串> 嵌套 = 数组清单.从(名单.取出(0), "戊");
打印行("嵌套 {嵌套.元素数()} 个：{嵌套}");
